class IO(base.IO):
    """Exact additional SQL; the old review Audit query must exclude Q Audits."""
    def __init__(self, c):
        super().__init__(c); self.qualifications = []

    def scalars(self, statement):
        if self.failure is not None: raise self.failure
        p = self.c.p
        old_audit = select(m.Audit).where(m.Audit.workspace_id == p.workspace_id,
            m.Audit.action.in_([reviews.COMMAND_AUDIT, reviews.STATE_AUDIT]),
            or_(m.Audit.actor_id == p.user_id, m.Audit.data['actor_id'].as_string() == p.user_id))
        choices = [(old_audit, [row for row in self.events if row.workspace_id == p.workspace_id
            and row.action in {reviews.COMMAND_AUDIT, reviews.STATE_AUDIT}
            and (row.actor_id == p.user_id or row.data.get('actor_id') == p.user_id)]),
            (select(Qualification).where(Qualification.workspace_id == p.workspace_id,
                Qualification.actor_id == p.user_id), [row for row in self.qualifications
                if row.workspace_id == p.workspace_id and row.actor_id == p.user_id]),
            (select(m.Audit).where(m.Audit.workspace_id == p.workspace_id, m.Audit.action == q.AUDIT,
                or_(m.Audit.actor_id == p.user_id, m.Audit.data['actor_id'].as_string() == p.user_id)),
                [row for row in self.events if row.workspace_id == p.workspace_id and row.action == q.AUDIT
                    and (row.actor_id == p.user_id or row.data.get('actor_id') == p.user_id)])]
        for label in ('qfirst', 'qsecond', 'qunknown', 'first', 'second'):
            nonce = identity(label)
            choices.extend([
                (select(Qualification).where(Qualification.workspace_id == p.workspace_id,
                    Qualification.request_id == nonce), [row for row in self.qualifications
                    if row.workspace_id == p.workspace_id and row.request_id == nonce]),
                (select(m.Audit).where(m.Audit.workspace_id == p.workspace_id,
                    m.Audit.action == q.AUDIT, m.Audit.data['request_id'].as_string() == nonce),
                    [row for row in self.events if row.workspace_id == p.workspace_id
                        and row.action == q.AUDIT and row.data.get('request_id') == nonce])])
        for label in ('first', 'second', 'third', 'unknown', 'other', 'new'):
            nonce = identity(label)
            choices.append((select(m.Audit).where(m.Audit.workspace_id == p.workspace_id,
                m.Audit.action.in_([reviews.COMMAND_AUDIT, reviews.STATE_AUDIT]),
                m.Audit.data['request_id'].as_string() == nonce),
                [row for row in self.events if row.workspace_id == p.workspace_id
                    and row.action in {reviews.COMMAND_AUDIT, reviews.STATE_AUDIT}
                    and row.data.get('request_id') == nonce]))
        for expected, result in choices:
            if matches_statement(statement, expected):
                equal_statement(statement, expected); return list(result)
        return super().scalars(statement)

    def add(self, row):
        if isinstance(row, Qualification): self.qualifications.append(row)
        else: return super().add(row)


def scene():
    c = base.scene(); db = IO(c)
    request = base.body(value={'public_synthetic_saved_value': {'int': 1, 'bool': True}}, note='不能默认共享的私人核对笔记')
    base.save(c, db, request)
    return c, db, reviews.get(db, c.p, c.attempt.id)


def trusted_source(saved):
    # The eight-key caller contract does NOT itself prove source authority.
    return {'schema': 'business-flow-author-review-source-v1', 'attempt_id': saved['attempt_id'],
        'source_binding_hash': digest(saved['source_binding']), 'value_hash': digest(saved['value']),
        'diagnostic_context_hash': digest({'public_synthetic_context': True}),
        'original_source_hash': 'f' * 64, 'current_source_hash': 'f' * 64,
        'current_materials_hash': digest({'public_synthetic_materials': True})}


def body(saved, label='qfirst'):
    return {'schema': q.COMMAND_SCHEMA, 'request_id': identity(label),
        'expected_version': saved['version'], 'save_request_id': saved['history'][-1]['request_id'],
        'value_hash': digest(saved['value']), 'ack_scope': True, 'ack_inferences': True,
        'reason': '作者仅自核此公开合成稿；存储测试不证明真实业务语义。'}


def create(c, db, saved, request=None, source=None):
    request = body(saved) if request is None else request
    return q.create(db, c.p, c.attempt.id, wire(request), method='POST', path=q.qualify_path(c.attempt.id),
        saved=saved, source_snapshot=trusted_source(saved) if source is None else source)


def test_immutable_author_record_binds_actual_saved_command_and_both_audits_without_mutation():
    c, db, saved = scene(); original = canonical_json([db.drafts[0].data, c.attempt.data, c.baseline])
    request = body(saved); result = create(c, db, saved, request)
    assert set(result) == {'schema', 'id', 'version', 'status', 'attempt_id', 'draft_id', 'draft_version',
        'save_request_id', 'request_id', 'value_hash', 'qualification_hash', 'source_snapshot_hash',
        'review_record_hash', 'human_review', 'reviewed_by', 'reviewed_at', 'value', 'source_binding',
        'baseline_hash', 'source_snapshot', 'ack_scope', 'ack_inferences', 'reason', *reviews.FLAGS}
    assert result['schema'] == q.RESULT and result['status'] == 'qualified' and result['version'] == 1
    assert result['human_review'] == 'author_self_reviewed' and result['reviewed_by'] == c.p.user_id
    assert result['value'] == saved['value'] and result['source_binding'] == saved['source_binding']
    assert result['draft_version'] == 1 and result['save_request_id'] == saved['history'][-1]['request_id']
    assert result['ack_scope'] is result['ack_inferences'] is True
    assert all(result[key] is False for key in reviews.FLAGS)
    assert '不能默认共享的私人核对笔记' not in canonical_json(result)
    row = db.qualifications[0]; original_command = db.commands[0]
    assert row.save_command_id == original_command.id
    assert row.data['record']['save_command_hash'] == original_command.command_hash
    assert row.data['record']['save_body_sha256'] == original_command.body_sha256
    assert result['review_record_hash'] == digest(original_command.data['record_snapshot'])
    assert canonical_json([db.drafts[0].data, c.attempt.data, c.baseline]) == original
    assert db.drafts[0].status == 'incomplete' and c.attempt.status == 'failed'
    assert len(db.qualifications) == 1 and len([event for event in db.events if event.action == q.AUDIT]) == 1
    assert db.commits == 2


@pytest.mark.parametrize('fault', ['schema', 'request_uuid', 'save_uuid', 'bool_version', 'zero_version',
    'float_version', 'value_hash', 'scope_false', 'inferences_false', 'int_ack', 'short_reason',
    'blank_reason', 'long_reason', 'extra_source', 'duplicate', 'nonfinite', 'utf8', 'too_large'])
def test_exact_wire_requires_explicit_human_acknowledgements_and_safe_original_json(fault):
    c, _, saved = scene(); value = body(saved)
    if fault == 'schema': value['schema'] = 'other'
    elif fault == 'request_uuid': value['request_id'] = 'not-a-uuid'
    elif fault == 'save_uuid': value['save_request_id'] = value['save_request_id'].upper()
    elif fault == 'bool_version': value['expected_version'] = True
    elif fault == 'zero_version': value['expected_version'] = 0
    elif fault == 'float_version': value['expected_version'] = 1.0
    elif fault == 'value_hash': value['value_hash'] = 'A' * 64
    elif fault == 'scope_false': value['ack_scope'] = False
    elif fault == 'inferences_false': value['ack_inferences'] = False
    elif fault == 'int_ack': value['ack_scope'] = 1
    elif fault == 'short_reason': value['reason'] = '一'
    elif fault == 'blank_reason': value['reason'] = '  '
    elif fault == 'long_reason': value['reason'] = 'x' * 12001
    elif fault == 'extra_source': value['source_snapshot'] = {}
    raw = wire(value)
    if fault == 'duplicate': raw = raw[:-1] + b',"ack_scope":true}'
    elif fault == 'nonfinite': raw = raw[:-1] + b',"unexpected":NaN}'
    elif fault == 'utf8': raw = b'\xff'
    elif fault == 'too_large': raw = b' ' * (q.MAX_WIRE_BYTES + 1)
    with pytest.raises(ValueError): q.parse_wire(raw)
    assert c.attempt.status == 'failed'


def test_original_nonce_returns_exact_qualified_version_after_later_draft_edits_and_source_unavailability():
    c, db, saved = scene(); request = body(saved); raw = wire(request); result = create(c, db, saved, request)
    # A later separate incomplete edit changes neither qualification nor raw answer.
    base.save(c, db, base.body('second', 1, {'later_human_work': 2}, '后来未完成笔记'))
    latest = reviews.get(db, c.p, c.attempt.id)
    assert latest['version'] == 2 and latest['value'] != result['value']
    assert q.get(db, c.p, result['id']) == result
    assert q.list_records(db, c.p, attempt_id=c.attempt.id) == [result]
    original = q.original_request(db, c.p, request['request_id'], hashlib.sha256(raw).hexdigest())
    assert original == {'schema': q.REQUEST, 'request_id': request['request_id'], 'found': True,
        'body_sha256': hashlib.sha256(raw).hexdigest(), 'result': result}
    assert q.replay(db, c.p, c.attempt.id, raw, method='POST', path=q.qualify_path(c.attempt.id)) == result
    # Historical recovery exits before considering new source/saved arguments.
    assert q.create(db, c.p, c.attempt.id, raw, method='POST', path=q.qualify_path(c.attempt.id),
        saved=None, source_snapshot=None) == result
    assert len(db.qualifications) == 1 and db.commits == 3
    cold = IO(c); cold.drafts = copy.deepcopy(db.drafts); cold.commands = copy.deepcopy(db.commands)
    cold.events = copy.deepcopy(db.events); cold.qualifications = copy.deepcopy(db.qualifications)
    assert q.original_request(cold, c.p, request['request_id'], hashlib.sha256(raw).hexdigest())['result'] == result
    assert q.get(cold, c.p, result['id']) == result and cold.commits == 0


@pytest.mark.parametrize('fault', ['version', 'save_request', 'value_hash'])
def test_only_known_unsaved_conflicts_get_explicit_not_applied(fault):
    c, db, saved = scene(); request = body(saved)
    if fault == 'version': request['expected_version'] = 2
    elif fault == 'save_request': request['save_request_id'] = identity('unknown')
    else: request['value_hash'] = '0' * 64
    with pytest.raises(HTTPException) as conflict: create(c, db, saved, request)
    assert conflict.value.status_code == 409 and conflict.value.detail == {
        'code': 'business_flow_author_review_version_conflict', 'not_applied': True, 'current_version': 1}
    assert q.original_request(db, c.p, request['request_id'], hashlib.sha256(wire(request)).hexdigest())['found'] is False
    assert not db.qualifications and db.commits == 1


