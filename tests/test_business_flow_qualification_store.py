def test_workspace_membership_and_actor_changes_cannot_borrow_qualification():
    c, db, saved = scene(); request = body(saved); result = create(c, db, saved, request)
    db.membership_role = 'viewer'
    with pytest.raises(HTTPException) as stale: q.get(db, c.p, result['id'])
    assert stale.value.status_code == 403
    c.p.role = 'viewer'
    assert q.original_request(db, c.p, request['request_id'], hashlib.sha256(wire(request)).hexdigest())['result'] == result
    second = body(saved, 'qsecond')
    with pytest.raises(HTTPException) as denied: create(c, db, saved, second)
    assert denied.value.status_code == 403
    c.p.workspace_id = identity('foreign-workspace')
    assert q.original_request(db, c.p, request['request_id'], hashlib.sha256(wire(request)).hexdigest())['found'] is False
    with pytest.raises(HTTPException) as absent: q.get(db, c.p, result['id'])
    assert absent.value.status_code == 404 and db.commits == 2


